function trPat(s){
  for(const [re, out] of EN_PAT){ if(re.test(s)) return s.replace(re, out); }
  return null;
}

/* Les noms de temps apparaissent aussi au milieu d'une définition */
function trTense(s){
  let out = s;
  Object.keys(TENSE_EN).forEach(fr => {
    out = out.replace(new RegExp("· " + fr + "(\\b|$)", "g"), "· " + TENSE_EN[fr]);
  });
  return out === s ? null : out;
}

const INLINE = {B:1, I:1, EM:1, STRONG:1};
function swappable(el){
  if(!el.children.length) return true;
  return [...el.children].every(c => INLINE[c.tagName] && !c.id);
}

/* Certains libellés vivent au milieu d'icônes et de numéros : on ne touche
   alors qu'au nœud de texte, jamais à la structure autour. */
function walkText(root){
  if(!root || !root.nodeType) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const hits = [];
  while(w.nextNode()) hits.push(w.currentNode);
  hits.forEach(n => {
    const p = n.parentElement;
    if(!p || p.tagName === "SCRIPT" || p.tagName === "STYLE" || p.tagName === "TEXTAREA") return;
    if(p.closest("[lang='fr'],[data-keep]")) return;
    if(LANG === "en"){
      const t = trTense(n.nodeValue);
      if(t && t !== n.nodeValue){
        if(n.__fr == null) n.__fr = n.nodeValue;
        n.nodeValue = t;
      }
    }else if(n.__fr != null){ n.nodeValue = n.__fr; n.__fr = null; }
  });
}

let painting = false;

function applyLang(root){
  painting = true;
  const scope = root || document.body;
  const all = scope.querySelectorAll ? [...scope.querySelectorAll("*")] : [];
  if(scope.nodeType === 1) all.unshift(scope);
  all.forEach(el => {
    if(el.tagName === "SCRIPT" || el.tagName === "STYLE") return;
    /* le vocabulaire et ce que tu as écrit toi-même ne se traduisent jamais */
    if(el.closest && el.closest("[lang='fr'],[data-keep]")) return;
    if(el.placeholder && EN_PH[el.placeholder]){
      el.dataset.phFr = el.placeholder;
      el.placeholder = EN_PH[el.placeholder];
    }else if(LANG === "fr" && el.dataset.phFr){
      el.placeholder = el.dataset.phFr;
      delete el.dataset.phFr;
    }
    if(!swappable(el)) return;
    const t = el.textContent.replace(/\s+/g, " ").trim();
    if(LANG === "en"){
      const hit = EN[t] || trPat(t) || trTense(t);
      if(hit && hit !== t){ if(!el.dataset.fr) el.dataset.fr = el.textContent; el.textContent = hit; }
    }else if(el.dataset.fr){
      el.textContent = el.dataset.fr;
      delete el.dataset.fr;
    }
  });
  walkText(scope);
  painting = false;
}

function setLang(l){
  LANG = l;
  try{ localStorage.setItem("le-cahier-lang", l); }catch(e){}
  if(l === "fr"){
    painting = true;
    document.querySelectorAll("[data-fr]").forEach(el => {
      el.textContent = el.dataset.fr; delete el.dataset.fr;
    });
    document.querySelectorAll("[data-ph-fr]").forEach(el => {
      el.placeholder = el.dataset.phFr; delete el.dataset.phFr;
    });
    walkText(document.body);
    painting = false;
  }else applyLang();
  const b = document.getElementById("langBtn");
  if(b){
    b.textContent = l === "en" ? "FR" : "EN";
    b.title = l === "en" ? "Passer l'interface en français" : "Switch the interface to English";
  }
  if(typeof paintMargin === "function") paintMargin();
}

function langInit(){
  try{
    const saved = localStorage.getItem("le-cahier-lang");
    if(saved === "fr" || saved === "en") LANG = saved;
  }catch(e){}
  const b = document.getElementById("langBtn");
  if(b) b.addEventListener("click", () => setLang(LANG === "en" ? "fr" : "en"));
  setLang(LANG);

  // les panneaux se redessinent sans cesse : on retraduit ce qui apparaît
  new MutationObserver((muts) => {
    if(painting || LANG !== "en") return;
    muts.forEach(m => {
      if(m.type === "childList"){
        let text = false;
        m.addedNodes.forEach(n => {
          if(n.nodeType === 1) applyLang(n);
          else if(n.nodeType === 3) text = true;
        });
        if(text && m.target && m.target.nodeType === 1) applyLang(m.target);
      }else if(m.target && m.target.nodeType === 3 && m.target.parentElement){
        applyLang(m.target.parentElement);
      }
    });
  }).observe(document.body, {childList:true, subtree:true, characterData:true});
}
